CREATE TABLE schema_migration (
    version integer PRIMARY KEY,
    description varchar(200) NOT NULL,
    applied_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE person (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    benutzername varchar(50) NOT NULL UNIQUE,
    CONSTRAINT person_name_valid CHECK (
        length(btrim(benutzername)) > 0 AND benutzername = btrim(benutzername)
    )
);

CREATE UNIQUE INDEX person_name_case_insensitive ON person (lower(benutzername));

CREATE TABLE geisternetz (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    breitengrad numeric(9,6) NOT NULL,
    laengengrad numeric(9,6) NOT NULL,
    geschaetzte_groesse_m2 numeric(12,2) NOT NULL,
    beschreibung text,
    status varchar(30) NOT NULL,
    meldende_person_id bigint REFERENCES person(id) ON DELETE RESTRICT,
    bergende_person_id bigint REFERENCES person(id) ON DELETE RESTRICT,
    gemeldet_am timestamptz NOT NULL,
    uebernommen_am timestamptz,
    geborgen_am timestamptz,
    verschollen_am timestamptz,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT netz_latitude CHECK (breitengrad BETWEEN -90 AND 90 AND breitengrad <> 'NaN'::numeric),
    CONSTRAINT netz_longitude CHECK (laengengrad BETWEEN -180 AND 180 AND laengengrad <> 'NaN'::numeric),
    CONSTRAINT netz_size CHECK (geschaetzte_groesse_m2 > 0 AND geschaetzte_groesse_m2 <> 'NaN'::numeric),
    CONSTRAINT netz_version CHECK (version >= 0),
    CONSTRAINT netz_status CHECK (status IN ('GEMELDET', 'BERGUNG_BEVORSTEHEND', 'GEBORGEN', 'VERSCHOLLEN')),
    CONSTRAINT netz_assignment CHECK (
        (bergende_person_id IS NULL AND uebernommen_am IS NULL)
        OR (bergende_person_id IS NOT NULL AND uebernommen_am IS NOT NULL)
    ),
    CONSTRAINT netz_lifecycle CHECK (
        (status = 'GEMELDET' AND bergende_person_id IS NULL AND geborgen_am IS NULL AND verschollen_am IS NULL)
        OR (status = 'BERGUNG_BEVORSTEHEND' AND bergende_person_id IS NOT NULL AND geborgen_am IS NULL AND verschollen_am IS NULL)
        OR (status = 'GEBORGEN' AND bergende_person_id IS NOT NULL AND geborgen_am IS NOT NULL AND verschollen_am IS NULL)
        OR (status = 'VERSCHOLLEN' AND geborgen_am IS NULL AND verschollen_am IS NOT NULL)
    ),
    CONSTRAINT netz_chronology CHECK (
        (uebernommen_am IS NULL OR uebernommen_am >= gemeldet_am)
        AND (geborgen_am IS NULL OR geborgen_am >= uebernommen_am)
        AND (verschollen_am IS NULL OR verschollen_am >= gemeldet_am)
        AND (verschollen_am IS NULL OR uebernommen_am IS NULL OR verschollen_am >= uebernommen_am)
    )
);

CREATE INDEX netz_status_idx ON geisternetz(status);
CREATE INDEX netz_bergende_person_idx ON geisternetz(bergende_person_id);
CREATE INDEX netz_meldende_person_idx ON geisternetz(meldende_person_id);

